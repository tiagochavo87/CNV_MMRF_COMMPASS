def classificar_cnv_detalhada(segment_mean):
    """Classifies the CNV type into 6 categories based on Segment_Mean."""
    # "Classifica o tipo de CNV em 6 categorias com base em Segment_Mean."
    if segment_mean <= LIMIAR_PERDA_HOMOZIGOTA:
        return 'Homozygous Deletion (0 Copies)' # 'Deleção Homozigota (0 Copias)'
    elif segment_mean <= LIMIAR_PERDA_1_COPIA:
        return '1-Copy Loss (1 Copy)' # 'Deleção de 1 Cópia (1 Cópia)'

