# --- Tenth block: Analyzing CNV segment frequency and characterization (Simple classification) ---
import pandas as pd

input_file = "combined_cnvs_classified.txt"  # classified file, with CNV_Type
# arquivo classificado, com CNV_Type

df = pd.read_csv(input_file, sep='\t')

# Check if the CNV_Type column exists
# Verifica se a coluna CNV_Type existe
if 'CNV_Type' not in df.columns:
    print("Column 'CNV_Type' not found in the file. Please use the classified file.")
    # "Column 'CNV_Type' não encontrada no arquivo. Por favor, use o arquivo classificado."
else:
    # Create SegmentID column by concatenating coordinates
    # Cria coluna SegmentID com concatenação das coordenadas
    df['SegmentID'] = df['Chromosome'].astype(str) + ":" + df['Start'].astype(str) + "-" + df['End'].astype(str)

    # Count occurrences grouping by SegmentID and CNV_Type
    # Conta ocorrências agrupando por SegmentID e CNV_Type
    segment_counts = df.groupby(['SegmentID', 'CNV_Type']).size().reset_index(name='Count')

    total_counts = segment_counts['Count'].sum()
    segment_counts['Frequency'] = segment_counts['Count'] / total_counts

    # Function to characterize CNV
    # Função para caracterizar CNV
    def characterize_cnv(cnv_type):
        if 'homozygous deletion' in cnv_type.lower() or 'deleção homozigota' in cnv_type.lower():
            return "Complete loss of genetic material" # "Perda completa de material genético"
