LIMIAR_PERDA_1_COPIA = -0.5    # Between -1.5 and -0.5 (Around theoretical -1.0)

# Neutral
# Neutro
LIMIAR_NEUTRO_MAX = 0.2
LIMIAR_NEUTRO_MIN = -0.2

# Gain
# Ganho
LIMIAR_GANHO_2_COPIAS = 0.8    # > 0.8 (Around theoretical 1.0)
LIMIAR_GANHO_1_COPIA = 0.3     # Between 0.3 and 0.8 (Around theoretical 0.58)


# 2. Detailed Classification Function
