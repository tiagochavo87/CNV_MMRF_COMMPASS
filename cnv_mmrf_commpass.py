import os

folder = "mmrf_cnv_data"

output_txt = "combined_cnvs.txt"
output_csv = "combined_cnvs.csv"
output_seg = "combined_cnvs.seg"

# List files with .seg or .seg.txt extension
# Lista arquivos com extensão .seg ou .seg.txt
files = [f for f in os.listdir(folder) if f.endswith(".seg") or f.endswith(".seg.txt")]
print(f"Files found to combine: {len(files)}")

# Function to convert a tab-separated line to CSV (comma-separated)
# Função para converter uma linha tabulada para CSV (separada por vírgula)
def to_csv_line(line):
    return ','.join(line.strip().split('\t')) + '\n'

# Function to read non-empty lines from a file
# Função para ler linhas não vazias de um arquivo
def read_non_empty_lines(path):
    with open(path, "r") as f:
        # Remove empty lines or lines with only whitespace
        # Remove linhas vazias ou com espaços em branco
        lines = [line for line in f if line.strip()]
    return lines

# Combine files into three different formats
# Combina arquivos em três formatos diferentes
with open(output_txt, "w") as out_txt, open(output_csv, "w") as out_csv, open(output_seg, "w") as out_seg:
    for i, filename in enumerate(files):
        path = os.path.join(folder, filename)
        lines = read_non_empty_lines(path)
        print(f"Reading file {filename} with {len(lines)} non-empty lines.")

        if not lines:
            print(f"Warning: file {filename} is empty or only has blank lines, skipping.")
            continue

        # Pure TXT and SEG: maintains tabs, includes header only once
        # TXT puro e SEG: mantém tabs, inclui cabeçalho só 1x
        if i == 0:
            out_txt.writelines(lines)
            out_seg.writelines(lines)
        else:
            out_txt.writelines(lines[1:])
            out_seg.writelines(lines[1:])

        # CSV converts tabs to commas
        # CSV converte tabs em vírgulas
        if i == 0:
            out_csv.write(to_csv_line(lines[0]))
        out_csv.writelines([to_csv_line(l) for l in lines[1:]])

print(f"Combination complete: files saved as {output_txt}, {output_csv}, {output_seg}")

print("\nExample of the first lines of the combined CSV file:")
with open(output_csv, "r") as f:
    for _ in range(10):
        print(f.readline().strip())

